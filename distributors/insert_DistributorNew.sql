    BEGIN TRANSACTION;

    DECLARE @RowsInserted INT = 0;
    DECLARE @RowsSkipped INT = 0;

    SELECT
        s.[Distributor],
        @DefaultSubRegionId AS SubRegionId,
        @DefaultStatus AS [status]
    FROM @Source s
    WHERE NOT EXISTS (
        SELECT 1
        FROM [dbo].[Distributors] d
