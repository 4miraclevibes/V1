        [Distributor],
        [SubRegionId],
        [code],
        [DistributorScm],
        [status]
    )
    SELECT
        s.[Distributor],
        @DefaultSubRegionId,
        NULL,
        NULL,
        @DefaultStatus
    FROM @Source s
    WHERE NOT EXISTS (
        SELECT 1
        FROM [dbo].[Distributors] d
        WHERE LTRIM(RTRIM(d.[Distributor])) COLLATE Latin1_General_CI_AI
            = s.[Distributor] COLLATE Latin1_General_CI_AI
    );

    SET @RowsInserted = @@ROWCOUNT;

    SELECT @RowsSkipped = COUNT(*)
    FROM @Source s
    WHERE EXISTS (
        SELECT 1
        FROM [dbo].[Distributors] d
        WHERE LTRIM(RTRIM(d.[Distributor])) COLLATE Latin1_General_CI_AI
            = s.[Distributor] COLLATE Latin1_General_CI_AI
    );

    COMMIT TRANSACTION;

    SELECT
        @RowsInserted AS RowsInserted,
        @RowsSkipped AS RowsSkipped,
        (SELECT COUNT(*) FROM @Source) AS TotalSourceRows,
